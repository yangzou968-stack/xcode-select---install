/**
 * 智能回复生成器 —— 三层回退架构 V4.0
 *
 * 优先级: 远程话术库 > LLM大模型(带上下文) > 本地多变体兜底
 *
 * V4.0 升级：
 * - 支持对话上下文传递给 LLM
 * - 本地话术每类 3 个变体随机选择
 * - 关键词匹配更精准
 * - 新增邪淫/失眠/职场等细分场景
 */
object ReplyGenerator {

    private var library: ScriptLibrary? = null
    private var isInitialized = false

    /**
     * 初始化：加载配置 + 同步远程话术库
     */
    suspend fun init(context: Context) {
        if (isInitialized) return
        try {
            com.juexin.assistant.network.AppConfig.load(context)
            try {
                library = ScriptRepository.syncFromRemote(context)
            } catch (_: Exception) { }
            isInitialized = true
        } catch (_: Exception) {
            isInitialized = true
        }
    }

    /**
     * V4.0 核心方法：生成回复（带对话上下文）
     *
     * @param context Android Context
     * @param userMessage 当前信众消息
     * @param conversationHistory 最近对话历史（格式："弟子：xxx\n师父：xxx\n..."）
     */
    suspend fun generateReply(
        context: Context,
        userMessage: String,
        conversationHistory: String = ""
    ): ReplyResult {
        // 确保已初始化
        if (!isInitialized) {
            try { init(context) } catch (_: Exception) { }
        }

        // 第1层：远程话术库关键词匹配
        library?.let { lib ->
            val matched = ScriptRepository.matchTemplate(lib, userMessage)
            if (matched != null) {
                return ReplyResult(
                    compassion = matched.compassion,
                    karma = matched.karma,
                    action = matched.action,
                    source = ReplySource.REMOTE_SCRIPT
                )
            }
        }

        // 第2层：LLM 大模型生成（带对话上下文）
        if (LlmClient.isAvailable()) {
            try {
                val llmReply = withTimeout(15000L) {
                    LlmClient.generateReply(userMessage, conversationHistory)
                }
                if (llmReply != null) {
                    return ReplyResult(
                        compassion = llmReply.compassion,
                        karma = llmReply.karma,
                        action = llmReply.action,
                        source = ReplySource.LLM
                    )
                }
                // LLM 返回 null，记录失败原因
                val err = LlmClient.lastError.ifBlank { "AI 返回空内容" }
                return localFallbackWithError(userMessage, err)
            } catch (e: java.util.concurrent.TimeoutException) {
                return localFallbackWithError(userMessage, "AI 请求超时")
            } catch (e: Exception) {
                val err = LlmClient.lastError.ifBlank { e.message ?: "AI 调用异常" }
                return localFallbackWithError(userMessage, err)
            }
        } else {
            // LLM 未配置
            val local = matchLocalWithVariant(userMessage)
            return ReplyResult(
                compassion = local.compassion,
                karma = local.karma,
                action = local.action,
                source = ReplySource.LOCAL_FALLBACK,
                llmError = "AI 未配置（请在设置中填写 API Key）"
            )
        }
    }

    /**
     * LLM 失败时的本地兜底，携带错误原因供 UI 提示
     */
    private fun localFallbackWithError(userMessage: String, llmError: String): ReplyResult {
        val local = matchLocalWithVariant(userMessage)
        return ReplyResult(
            compassion = local.compassion,
            karma = local.karma,
            action = local.action,
            source = ReplySource.LOCAL_FALLBACK,
            llmError = llmError
        )
    }

    /**
     * 同步方法：仅本地话术（不依赖 context，不调网络/LLM）
     * 供悬浮球快速降级使用
     */
    fun generate(userMessage: String): ReplyResult {
        val local = matchLocalWithVariant(userMessage)
        return ReplyResult(
            compassion = local.compassion,
            karma = local.karma,
            action = local.action,
            source = ReplySource.LOCAL_FALLBACK
        )
    }

    /**
     * 强制同步话术库
     */
    suspend fun forceSync(context: Context): Boolean {
        return try {
            library = ScriptRepository.syncFromRemote(context)
            library != null
        } catch (e: Exception) {
            false
        }
    }

    fun getLibraryVersion(): Int = library?.version ?: 0

    // ==================== 本地多变体话术库 V4.0 ====================

    /**
     * 从一组变体中随机选一个
     */
    private fun pickRandom(variants: List<ScriptTemplate>): ScriptTemplate {
        return variants[Random.nextInt(variants.size)]
    }

    /**
     * 带变体随机选择的本地匹配
     */
    private fun matchLocalWithVariant(message: String): ScriptTemplate {
        val m = message.lowercase()

        // 财运类（3个变体）
        if (hasAny(m, "钱", "财", "穷", "亏", "负债", "债", "赌", "账")) {
            return pickRandom(WEALTH_VARIANTS)
        }

        // 堕胎/婴灵类
        if (hasAny(m, "堕胎", "流产", "打胎", "婴灵", "孩子没")) {
            return pickRandom(ABORTION_VARIANTS)
        }

        // 婚姻/感情类
        if (hasAny(m, "婚姻", "离婚", "出轨", "老公", "老婆", "夫妻", "感情", "分手", "小三")) {
            return pickRandom(MARRIAGE_VARIANTS)
        }

        // 子女类
        if (hasAny(m, "孩子", "儿子", "女儿", "不听话", "叛逆", "学习", "成绩")) {
            return pickRandom(CHILDREN_VARIANTS)
        }

        // 健康类
        if (hasAny(m, "病", "疼", "痛", "癌", "医院", "失眠", "抑郁", "焦虑", "累")) {
            return pickRandom(HEALTH_VARIANTS)
        }

        // 噩梦/鬼压床
        if (hasAny(m, "梦", "噩梦", "鬼", "鬼压床", "睡不好", "惊醒")) {
            return pickRandom(NIGHTMARE_VARIANTS)
        }

        // 亡亲/托梦
        if (hasAny(m, "去世", "过世", "托梦", "亡亲", "走")) {
            return pickRandom(DECEASED_VARIANTS)
        }

        // 邪淫类
        if (hasAny(m, "邪淫", "色情", "手淫", "意淫", "淫欲", "控制不住")) {
            return pickRandom(LUST_VARIANTS)
        }

        // 职场/事业
        if (hasAny(m, "工作", "失业", "老板", "同事", "辞职", "面试", "收入低")) {
            return pickRandom(CAREER_VARIANTS)
        }

        // 通用兜底（3个变体）
        return pickRandom(GENERIC_VARIANTS)
    }

    /** 简易多关键词匹配 */
    private fun hasAny(text: String, vararg keywords: String): Boolean {
        return keywords.any { text.contains(it) }
    }

